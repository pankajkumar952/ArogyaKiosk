/**
 * Get the offline fallback question for a stage and language.
 * Falls back to Hindi, then English if the specific language is not available.
 */
export function getOfflineFallback(stage: OfflineStage, lang: string): string {
  const stageMap = OFFLINE_QUESTIONS[stage];
  return (
    stageMap?.[lang as LangCode] ??
    stageMap?.["hi"] ??
    stageMap?.["en"] ??
    "आपको क्या तकलीफ है?"
  );
}
